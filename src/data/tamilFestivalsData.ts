/**
 * Filter festivals for a specific Gregorian year and month (1-12)
 */
export function getFestivalsForMonth(year: number, month: number): TamilFestival[] {
  const monthStr = String(month).padStart(2, '0');
  const prefix = `${year}-${monthStr}`;
  return TAMIL_FESTIVALS_DATABASE.filter((f) => f.date.startsWith(prefix));
}

/**
 * Get festivals for a specific date string (YYYY-MM-DD)
 */
export function getFestivalsForDate(dateStr: string): TamilFestival[] {
  return TAMIL_FESTIVALS_DATABASE.filter((f) => f.date === dateStr);
}
